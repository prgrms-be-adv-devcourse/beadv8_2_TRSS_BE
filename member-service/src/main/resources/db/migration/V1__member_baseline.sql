-- member 스키마 초기 상태. 모놀리스 마이그레이션 V1~V16 중 회원 테이블만 모아 최종 형태로 정리했다.
-- 운영 DB는 테이블을 public에서 member로 옮긴 뒤 baseline-on-migrate로 이 파일을 적용된 것으로 기록한다.
-- 그래서 이 파일은 옮긴 뒤의 운영 테이블과 같아야 한다. 이후 변경은 V2부터 새 파일로 추가한다.
--
-- 운영 이전 절차 (member-service를 처음 띄우기 전에 public 권한이 있는 계정으로 실행)
--   1. 회원 테이블 4개를 옮긴다. 테이블끼리의 FK(seller → member 등)는 함께 옮겨지고, identity 시퀀스도 테이블을 따라간다.
--        ALTER TABLE public.member SET SCHEMA member;   (seller, seller_status_history, member_social_account도 같은 방식)
--   2. outbox_event·processed_event는 모놀리스가 public에서 계속 쓰므로 옮기지 않고 구조만 복사한다.
--      회원은 받는 이벤트가 없어 processed_event에 옮길 기록은 없다.
--      아직 발행되지 않은(PENDING) 회원 이벤트(MemberSignedUpEvent·Seller*Event)가 public.outbox_event에 남아 있으면
--      모놀리스 릴레이가 마저 보내도록 member-service 전환 전에 PENDING이 비었는지 확인한다.
--        CREATE TABLE member.outbox_event (LIKE public.outbox_event INCLUDING ALL);
--        CREATE TABLE member.processed_event (LIKE public.processed_event INCLUDING ALL);
--   3. 옮기거나 만든 테이블·시퀀스의 소유자를 member_user로 바꾼다(ALTER TABLE/SEQUENCE ... OWNER TO member_user).
--   빠뜨리면 ddl-auto: validate가 앱 시작을 막는다(조용히 새로 만들지 않는다).
-- enum 컬럼에는 허용 값 CHECK 제약을 두지 않는다(모놀리스 V1과 같은 규칙).
-- 회원 테이블은 다른 서비스 테이블을 FK로 참조하지 않고, 다른 서비스 테이블도 회원 테이블을 FK로 참조하지 않는다.

-- ── 회원 ──

create table member (
    created_at timestamp(6) not null,
    deleted_at timestamp(6),
    id bigint generated by default as identity,
    updated_at timestamp(6) not null,
    name varchar(20) not null,
    role varchar(20) not null,
    status varchar(20) not null,
    email varchar(100) not null unique,
    password varchar(255) not null,
    primary key (id)
);

-- 이메일은 소문자로 저장하고, 대소문자만 다른 중복 가입을 막는다 (모놀리스 V2)
create unique index uk_member_email_lower on member (lower(email));

-- 카카오 등 소셜 계정 연결 (모놀리스 V15)
create table member_social_account (
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    member_id bigint not null,
    updated_at timestamp(6) not null,
    provider varchar(20) not null,
    provider_user_id varchar(100) not null,
    primary key (id),
    constraint uk_member_social_account_provider_user unique (provider, provider_user_id),
    constraint uk_member_social_account_member_provider unique (member_id, provider)
);

alter table member_social_account
   add constraint fk_member_social_account_member_id
   foreign key (member_id)
   references member;

-- ── 판매자 ──

create table seller (
    applied_at timestamp(6) not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    member_id bigint not null unique,
    updated_at timestamp(6) not null,
    version bigint not null,
    business_number varchar(20) unique,
    phone_number varchar(20) not null,
    bank_name varchar(30) not null,
    status varchar(30) not null,
    account_holder varchar(50) not null,
    representative_name varchar(50) not null,
    business_name varchar(100) not null,
    account_number varchar(255) not null,
    approved_at timestamp(6),
    primary key (id)
);

alter table seller
   add constraint fk_seller_member_id
   foreign key (member_id)
   references member;

create table seller_status_history (
    account_last4 varchar(4),
    changed_at timestamp(6) not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    seller_id bigint not null,
    updated_at timestamp(6) not null,
    business_number varchar(20),
    from_status varchar(30),
    to_status varchar(30) not null,
    representative_name varchar(50),
    business_name varchar(100),
    reason varchar(255),
    primary key (id)
);

create index idx_seller_status_history_seller
   on seller_status_history (seller_id, id);

alter table seller_status_history
   add constraint fk_seller_status_history_seller_id
   foreign key (seller_id)
   references seller;

-- ── 이벤트 (서비스마다 자기 스키마에 둔다) ──

-- Outbox: 비즈니스 변경과 같은 트랜잭션에 이벤트를 저장해 두고, 릴레이가 나중에 발행한다
create table outbox_event (
    aggregate_id bigint not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    occurred_at timestamp(6) not null,
    published_at timestamp(6),
    retry_count integer not null default 0,
    updated_at timestamp(6) not null,
    event_id uuid not null,
    aggregate_type varchar(30) not null,
    event_type varchar(100) not null,
    status varchar(20) not null,
    payload jsonb not null,
    primary key (id),
    constraint uk_outbox_event_event_id unique (event_id)
);

create index idx_outbox_event_pending
   on outbox_event (id)
   where status = 'PENDING';

create index idx_outbox_event_aggregate
   on outbox_event (aggregate_type, aggregate_id);

-- Kafka 컨슈머가 처리한 이벤트 기록. 회원은 지금 받는 이벤트가 없지만 공통 컨슈머 설정(ProcessedEvents)이 이 테이블을 쓴다
create table processed_event (
    event_id uuid not null,
    consumer varchar(100) not null,
    processed_at timestamp(6) not null,
    primary key (event_id, consumer)
);
