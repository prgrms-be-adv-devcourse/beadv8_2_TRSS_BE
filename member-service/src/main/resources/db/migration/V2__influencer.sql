create table influencer (
    applied_at timestamp(6) not null,
    created_at timestamp(6) not null,
    decided_at timestamp(6),
    id bigint generated by default as identity,
    member_id bigint not null unique,
    updated_at timestamp(6) not null,
    version bigint not null,
    status varchar(30) not null,
    activity_name varchar(30) not null,
    introduction varchar(500) not null,
    sns_url varchar(500) not null,
    primary key (id)
);

alter table influencer
   add constraint fk_influencer_member_id
   foreign key (member_id)
   references member;

create table influencer_status_history (
    changed_at timestamp(6) not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    influencer_id bigint not null,
    updated_at timestamp(6) not null,
    from_status varchar(30),
    to_status varchar(30) not null,
    reason varchar(255),
    primary key (id)
);

create index idx_influencer_status_history_influencer
   on influencer_status_history (influencer_id, id);

alter table influencer_status_history
   add constraint fk_influencer_status_history_influencer_id
   foreign key (influencer_id)
   references influencer;
