-- settlement 스키마 초기 상태. 모놀리스 마이그레이션 V1~V16 중 정산 테이블만 모아 최종 형태로 정리했다.
-- 운영 DB는 테이블을 public에서 settlement로 옮긴 뒤 baseline-on-migrate로 이 파일을 적용된 것으로 기록한다.
-- 그래서 이 파일은 옮긴 뒤의 운영 테이블과 같아야 한다. 이후 변경은 V2부터 새 파일로 추가한다.
--
-- 운영 이전 절차 (settlement-service를 처음 띄우기 전에 public 권한이 있는 계정으로 실행)
--   1. 정산 테이블 3개와 Spring Batch 메타 테이블 6개·시퀀스 3개를 옮긴다. 메타 테이블을 그대로 가져가야
--      이미 실행한 월 정산 Job이 다시 실행되지 않고, 실행 ID가 이어져 settlement_process_history.batch_execution_id와 맞는다.
--        ALTER TABLE public.settlement SET SCHEMA settlement;   (나머지 테이블도 같은 방식)
--        ALTER SEQUENCE public.batch_job_execution_seq SET SCHEMA settlement;   (나머지 시퀀스도 같은 방식)
--   2. outbox_event·processed_event는 모놀리스가 public에서 계속 쓰므로 옮기지 않고 구조만 복사한다.
--      processed_event에는 정산 컨슈머 기록을 옮겨, 이미 처리한 OrderConfirmedEvent를 다시 처리하지 않게 한다.
--        CREATE TABLE settlement.outbox_event (LIKE public.outbox_event INCLUDING ALL);
--        CREATE TABLE settlement.processed_event (LIKE public.processed_event INCLUDING ALL);
--        INSERT INTO settlement.processed_event SELECT * FROM public.processed_event WHERE consumer = 'settlement';
--   3. 옮기거나 만든 테이블·시퀀스의 소유자를 settlement_user로 바꾼다(ALTER TABLE/SEQUENCE ... OWNER TO settlement_user).
--   빠뜨리면 outbox_event는 ddl-auto: validate가 앱 시작을 막고, 메타 테이블은 Job 실행 시 오류가 난다(조용히 새로 만들지 않는다).
-- enum 컬럼에는 허용 값 CHECK 제약을 두지 않는다(모놀리스 V1과 같은 규칙).
-- 정산 테이블은 다른 서비스 테이블을 FK로 참조하지 않는다. seller_id·order_id·order_item_id는 값만 저장한다(논리적 참조).

-- ── 정산 ──

create table settlement (
    item_count integer not null,
    retry_count integer not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    next_retry_at timestamp(6),
    paid_at timestamp(6),
    payout_amount bigint not null,
    seller_id bigint not null,
    total_fee bigint not null,
    total_sale_price bigint not null,
    updated_at timestamp(6) not null,
    wallet_tx_id bigint,
    status varchar(20) not null,
    idempotency_key varchar(100),
    hold_reason varchar(300),
    last_fail_reason varchar(300),
    settlement_month CHAR(7) not null,
    primary key (id),
    constraint uk_settlement_seller_month unique (seller_id, settlement_month),
    constraint uk_settlement_idempotency_key unique (idempotency_key)
);

create table settlement_candidate (
    fee_rate integer not null,
    confirmed_at timestamp(6) not null,
    created_at timestamp(6) not null,
    fee bigint not null,
    id bigint generated by default as identity,
    order_id bigint not null,
    order_item_id bigint not null,
    outbox_event_id bigint,
    payout_amount bigint not null,
    sale_price bigint not null,
    seller_id bigint not null,
    settlement_id bigint,
    updated_at timestamp(6) not null,
    status varchar(20) not null,
    excluded_reason varchar(300),
    settlement_month CHAR(7) not null,
    primary key (id),
    constraint uk_candidate_order_item unique (order_item_id)
);

create table settlement_process_history (
    attempt_no integer not null,
    batch_execution_id bigint,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    processed_at timestamp(6) not null,
    target_id bigint,
    updated_at timestamp(6) not null,
    result varchar(20) not null,
    target_type varchar(20) not null,
    trigger_type varchar(20) not null,
    stage varchar(30) not null,
    error_code varchar(100),
    admin_reason varchar(300),
    fail_reason varchar(300),
    primary key (id)
);

create index idx_settlement_status
   on settlement (status, settlement_month);

create index idx_candidate_settlement
   on settlement_candidate (settlement_id);

create index idx_candidate_seller_status
   on settlement_candidate (seller_id, status, settlement_month);

create index idx_history_target
   on settlement_process_history (target_type, target_id);

alter table settlement_candidate
   add constraint fk_settlement_candidate_settlement_id
   foreign key (settlement_id)
   references settlement;

-- ── 이벤트 (서비스마다 자기 스키마에 둔다) ──

-- Outbox: 비즈니스 변경과 같은 트랜잭션에 이벤트를 저장해 두고, 릴레이가 나중에 발행한다
create table outbox_event (
    aggregate_id bigint not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    occurred_at timestamp(6) not null,
    published_at timestamp(6),
    retry_count integer not null default 0,
    updated_at timestamp(6) not null,
    event_id uuid not null,
    aggregate_type varchar(30) not null,
    event_type varchar(100) not null,
    status varchar(20) not null,
    payload jsonb not null,
    primary key (id),
    constraint uk_outbox_event_event_id unique (event_id)
);

create index idx_outbox_event_pending
   on outbox_event (id)
   where status = 'PENDING';

create index idx_outbox_event_aggregate
   on outbox_event (aggregate_type, aggregate_id);

-- Kafka 컨슈머가 처리한 이벤트 기록. 같은 이벤트를 두 번 받아도 한 번만 처리하게 한다
create table processed_event (
    event_id uuid not null,
    consumer varchar(100) not null,
    processed_at timestamp(6) not null,
    primary key (event_id, consumer)
);

-- ── Spring Batch 메타 테이블 (월 정산 Job) ──
-- spring-batch-core 6.0.5의 org/springframework/batch/core/schema-postgresql.sql을 그대로 옮겼다.
-- spring.batch.jdbc.initialize-schema=never라서 앱이 만들지 않고 이 파일로만 만든다.
-- Spring Batch 버전을 올려 메타 테이블 구조가 바뀌면, 그 버전의 마이그레이션 스크립트를 V2부터 새 파일로 추가한다.
-- 관리자 "월 정산 실행 이력" 조회(SettlementGetRunsUseCase)와 settlement_process_history.batch_execution_id가 이 테이블을 쓴다.

CREATE TABLE BATCH_JOB_INSTANCE (
	JOB_INSTANCE_ID BIGINT  NOT NULL PRIMARY KEY,
	VERSION BIGINT,
	JOB_NAME VARCHAR(100) NOT NULL,
	JOB_KEY VARCHAR(32) NOT NULL,
	constraint JOB_INST_UN unique (JOB_NAME, JOB_KEY)
) ;

CREATE TABLE BATCH_JOB_EXECUTION (
	JOB_EXECUTION_ID BIGINT  NOT NULL PRIMARY KEY,
	VERSION BIGINT,
	JOB_INSTANCE_ID BIGINT NOT NULL,
	CREATE_TIME TIMESTAMP NOT NULL,
	START_TIME TIMESTAMP DEFAULT NULL,
	END_TIME TIMESTAMP DEFAULT NULL,
	STATUS VARCHAR(10),
	EXIT_CODE VARCHAR(2500),
	EXIT_MESSAGE VARCHAR(2500),
	LAST_UPDATED TIMESTAMP,
	constraint JOB_INST_EXEC_FK foreign key (JOB_INSTANCE_ID)
	references BATCH_JOB_INSTANCE(JOB_INSTANCE_ID)
) ;

CREATE TABLE BATCH_JOB_EXECUTION_PARAMS (
	JOB_EXECUTION_ID BIGINT NOT NULL,
	PARAMETER_NAME VARCHAR(100) NOT NULL,
	PARAMETER_TYPE VARCHAR(100) NOT NULL,
	PARAMETER_VALUE VARCHAR(2500),
	IDENTIFYING CHAR(1) NOT NULL,
	constraint JOB_EXEC_PARAMS_FK foreign key (JOB_EXECUTION_ID)
	references BATCH_JOB_EXECUTION(JOB_EXECUTION_ID)
) ;

CREATE TABLE BATCH_STEP_EXECUTION (
	STEP_EXECUTION_ID BIGINT  NOT NULL PRIMARY KEY,
	VERSION BIGINT NOT NULL,
	STEP_NAME VARCHAR(100) NOT NULL,
	JOB_EXECUTION_ID BIGINT NOT NULL,
	CREATE_TIME TIMESTAMP NOT NULL,
	START_TIME TIMESTAMP DEFAULT NULL,
	END_TIME TIMESTAMP DEFAULT NULL,
	STATUS VARCHAR(10),
	COMMIT_COUNT BIGINT,
	READ_COUNT BIGINT,
	FILTER_COUNT BIGINT,
	WRITE_COUNT BIGINT,
	READ_SKIP_COUNT BIGINT,
	WRITE_SKIP_COUNT BIGINT,
	PROCESS_SKIP_COUNT BIGINT,
	ROLLBACK_COUNT BIGINT,
	EXIT_CODE VARCHAR(2500),
	EXIT_MESSAGE VARCHAR(2500),
	LAST_UPDATED TIMESTAMP,
	constraint JOB_EXEC_STEP_FK foreign key (JOB_EXECUTION_ID)
	references BATCH_JOB_EXECUTION(JOB_EXECUTION_ID)
) ;

CREATE TABLE BATCH_STEP_EXECUTION_CONTEXT (
	STEP_EXECUTION_ID BIGINT NOT NULL PRIMARY KEY,
	SHORT_CONTEXT VARCHAR(2500) NOT NULL,
	SERIALIZED_CONTEXT TEXT,
	constraint STEP_EXEC_CTX_FK foreign key (STEP_EXECUTION_ID)
	references BATCH_STEP_EXECUTION(STEP_EXECUTION_ID)
) ;

CREATE TABLE BATCH_JOB_EXECUTION_CONTEXT (
	JOB_EXECUTION_ID BIGINT NOT NULL PRIMARY KEY,
	SHORT_CONTEXT VARCHAR(2500) NOT NULL,
	SERIALIZED_CONTEXT TEXT,
	constraint JOB_EXEC_CTX_FK foreign key (JOB_EXECUTION_ID)
	references BATCH_JOB_EXECUTION(JOB_EXECUTION_ID)
) ;

CREATE SEQUENCE BATCH_STEP_EXECUTION_SEQ MAXVALUE 9223372036854775807 NO CYCLE;
CREATE SEQUENCE BATCH_JOB_EXECUTION_SEQ MAXVALUE 9223372036854775807 NO CYCLE;
CREATE SEQUENCE BATCH_JOB_INSTANCE_SEQ MAXVALUE 9223372036854775807 NO CYCLE;
