-- 쿠폰. 상품 쿠폰(판매자 등록)과 장바구니 쿠폰(관리자 등록)을 한 테이블에 둔다
-- status는 운영 상태(ACTIVE, STOPPED)만 저장한다. 시작 전(SCHEDULED)과 종료(ENDED)는 유효 기간과 현재 시각으로 계산한다
-- 유효 기간은 시작 포함, 종료 미포함(valid_from <= 현재 < valid_until)
create table coupon (
    quantity_limited boolean not null,
    remaining_quantity integer,
    total_quantity integer,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    issuer_id bigint not null,
    stopped_at timestamp(6),
    updated_at timestamp(6) not null,
    valid_from timestamp(6) not null,
    valid_until timestamp(6) not null,
    coupon_type varchar(20) not null,
    issuer_type varchar(20) not null,
    status varchar(20) not null,
    stopped_by varchar(20),
    name varchar(100) not null,
    stop_reason varchar(300),
    primary key (id),
    constraint ck_coupon_period check (valid_from < valid_until),
    -- 남은 수량은 조건부 UPDATE로만 바뀐다. 코드가 잘못돼도 음수나 총 수량 초과가 저장되지 않게 막는다
    constraint ck_coupon_remaining_quantity check (
        remaining_quantity is null or (remaining_quantity >= 0 and remaining_quantity <= total_quantity))
);

-- 관리자 목록(종류, 상태 필터)과 구매자 장바구니 쿠폰 목록(사용 가능 기간) 조회용
create index idx_coupon_type_status_valid on coupon (coupon_type, status, valid_until);

-- 장바구니 쿠폰 할인 구간 (구간마다 1행). 한 쿠폰 안에서 최소 주문 금액은 겹치지 않는다
create table cart_coupon_tier (
    coupon_id bigint not null,
    created_at timestamp(6) not null,
    discount_amount bigint not null,
    id bigint generated by default as identity,
    min_order_amount bigint not null,
    updated_at timestamp(6) not null,
    primary key (id),
    constraint uk_cart_coupon_tier_min_amount unique (coupon_id, min_order_amount)
);

alter table cart_coupon_tier
   add constraint fk_cart_coupon_tier_coupon_id
   foreign key (coupon_id)
   references coupon;

-- 회원별 쿠폰 사용 기록. 주문(market_order)은 다른 애그리거트라 FK를 두지 않는다
create table coupon_usage (
    coupon_id bigint not null,
    created_at timestamp(6) not null,
    discount_amount bigint not null,
    id bigint generated by default as identity,
    member_id bigint not null,
    order_id bigint not null,
    order_item_id bigint,
    released_at timestamp(6),
    reserved_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    used_at timestamp(6),
    status varchar(20) not null,
    primary key (id)
);

-- 1인 1회: 같은 쿠폰과 회원의 예약, 사용 기록은 하나만 둔다 (해제된 기록은 여러 개여도 된다)
-- 같은 회원의 주문 두 건이 동시에 같은 쿠폰을 예약해도 하나만 저장된다
create unique index uk_coupon_usage_member_active
   on coupon_usage (coupon_id, member_id)
   where status in ('RESERVED', 'USED');

create index idx_coupon_usage_member on coupon_usage (member_id, id);
create index idx_coupon_usage_order on coupon_usage (order_id);
create index idx_coupon_usage_coupon on coupon_usage (coupon_id, status);

alter table coupon_usage
   add constraint fk_coupon_usage_coupon_id
   foreign key (coupon_id)
   references coupon;
