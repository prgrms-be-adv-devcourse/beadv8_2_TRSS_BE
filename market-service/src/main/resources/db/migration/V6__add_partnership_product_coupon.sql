-- 판매자와 인플루언서의 협약. 진행 중(ACTIVE)인 협약이 있어야 상품 쿠폰을 발행할 수 있다
-- influencer_id는 인플루언서 ID(influencer.id)이고 회원 ID가 아니다. 인플루언서는 member-service에 있어 FK를 두지 않는다
create table partnership (
    accepted_at timestamp(6),
    created_at timestamp(6) not null,
    ended_at timestamp(6),
    id bigint generated by default as identity,
    influencer_id bigint not null,
    rejected_at timestamp(6),
    requested_at timestamp(6) not null,
    seller_id bigint not null,
    updated_at timestamp(6) not null,
    ended_by varchar(20),
    status varchar(20) not null,
    request_message varchar(500),
    primary key (id)
);

-- 같은 판매자와 인플루언서 사이에 요청 중이거나 진행 중인 협약은 하나만 둔다 (거절, 종료 뒤에는 다시 요청할 수 있다)
create unique index uk_partnership_open
   on partnership (seller_id, influencer_id)
   where status in ('REQUESTED', 'ACTIVE');

create index idx_partnership_seller on partnership (seller_id, id);
create index idx_partnership_influencer on partnership (influencer_id, id);

-- 상품 쿠폰 전용 정보. 공통 정보(쿠폰명, 기간, 수량, 상태)는 coupon에 있다
-- 쿠폰 1장 = 판매자 1명 x 인플루언서 1명 x 상품 1개, 쿠폰마다 코드 1개
create table product_coupon (
    coupon_id bigint not null,
    created_at timestamp(6) not null,
    discount_value bigint not null,
    id bigint generated by default as identity,
    influencer_id bigint not null,
    max_discount_amount bigint,
    partnership_id bigint not null,
    product_id bigint not null,
    updated_at timestamp(6) not null,
    code varchar(20) not null,
    discount_type varchar(20) not null,
    primary key (id),
    constraint uk_product_coupon_coupon_id unique (coupon_id),
    constraint uk_product_coupon_code unique (code),
    -- 할인 방식별 조건(정률 1~100%, 최대 할인액)은 앱에서 확인한다. enum 값을 CHECK에 넣지 않는 규칙이라 금액 범위만 막는다
    constraint ck_product_coupon_discount check (discount_value >= 1 and (max_discount_amount is null or max_discount_amount >= 1))
);

-- 기간 겹침 확인(같은 인플루언서, 같은 상품), 상품 판매 종료 때 자동 중지, 협약 종료 때 자동 중지
create index idx_product_coupon_influencer_product on product_coupon (influencer_id, product_id);
create index idx_product_coupon_product on product_coupon (product_id);
create index idx_product_coupon_partnership on product_coupon (partnership_id);

alter table product_coupon
   add constraint fk_product_coupon_coupon_id
   foreign key (coupon_id)
   references coupon;

alter table product_coupon
   add constraint fk_product_coupon_partnership_id
   foreign key (partnership_id)
   references partnership;

-- 한 주문에는 쿠폰 종류(상품, 장바구니)마다 1개만 쓸 수 있다(최대 2개). 판단용으로 사용 기록에 쿠폰 종류를 복사해 둔다
alter table coupon_usage add column coupon_type varchar(20);

update coupon_usage u
   set coupon_type = c.coupon_type
  from coupon c
 where c.id = u.coupon_id;

alter table coupon_usage alter column coupon_type set not null;

-- 같은 주문에 같은 종류의 예약, 사용 기록은 하나만 둔다 (해제된 기록은 빼서 다시 고를 수 있다)
create unique index uk_coupon_usage_order_type
   on coupon_usage (order_id, coupon_type)
   where status in ('RESERVED', 'USED');
