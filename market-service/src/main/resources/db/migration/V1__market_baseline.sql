-- market 스키마 초기 상태. 모놀리스 마이그레이션 V1~V16 중 market 테이블(상품·주문)만 모아 최종 형태로 정리했다.
-- 운영 DB는 테이블을 public에서 market으로 옮긴 뒤 baseline-on-migrate로 이 파일을 적용된 것으로 기록한다.
-- 그래서 이 파일은 옮긴 뒤의 운영 테이블과 같아야 한다. 이후 변경은 V2부터 새 파일로 추가한다.
-- enum 컬럼에는 허용 값 CHECK 제약을 두지 않는다(모놀리스 V1과 같은 규칙).

-- ── 상품 ──

create table category (
    is_active boolean not null,
    sort_order integer not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    parent_id bigint,
    updated_at timestamp(6) not null,
    name varchar(50) not null,
    primary key (id),
    -- 대분류(parent_id가 null)끼리도 같은 이름을 두 번 넣지 못하게 한다
    constraint uk_category_parent_name unique nulls not distinct (parent_id, name)
);

create table product (
    category_id bigint not null,
    created_at timestamp(6) not null,
    deleted_at timestamp(6),
    id bigint generated by default as identity,
    price bigint not null,
    seller_id bigint not null,
    stopped_at timestamp(6),
    updated_at timestamp(6) not null,
    version bigint not null,
    status varchar(20) not null,
    stopped_by varchar(20),
    name varchar(100) not null,
    stopped_reason varchar(300),
    description TEXT not null,
    primary key (id)
);

create table product_option (
    stock integer not null,
    created_at timestamp(6) not null,
    deleted_at timestamp(6),
    id bigint generated by default as identity,
    product_id bigint not null,
    updated_at timestamp(6) not null,
    name varchar(50) not null,
    primary key (id),
    -- 재고는 0 미만이 될 수 없다. 애플리케이션 검사를 우회한 쓰기도 DB에서 막는다
    constraint ck_product_option_stock check (stock >= 0)
);

-- 상품 이미지: 대표 이미지(THUMBNAIL) 1개와 상세 이미지(DETAIL) 최대 10개. 저장소 안의 키만 저장한다
create table product_image (
    sort_order integer not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    product_id bigint not null,
    updated_at timestamp(6) not null,
    image_type varchar(20) not null check (image_type in ('THUMBNAIL','DETAIL')),
    image_key varchar(300) not null,
    primary key (id)
);

-- 판매 중지 요청: 판매자가 사유와 함께 요청하고 관리자가 승인(상품 STOPPED)·반려한다
create table product_stop_request (
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    product_id bigint not null,
    reviewed_at timestamp(6),
    seller_id bigint not null,
    updated_at timestamp(6) not null,
    status varchar(20) not null check (status in ('PENDING','APPROVED','REJECTED','CANCELED')),
    reason varchar(300) not null,
    reject_reason varchar(300),
    primary key (id)
);

create table stock_history (
    change_qty integer not null,
    stock_after integer not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    option_id bigint not null,
    order_id bigint,
    order_item_id bigint,
    updated_at timestamp(6) not null,
    change_type varchar(20) not null,
    primary key (id),
    constraint uk_stock_history_order_item_change_type unique (order_item_id, change_type)
);

-- 품절 판단 서브쿼리는 상품으로 옵션을, 재고 이력 조회는 옵션으로 이력을 찾는다
create index idx_product_option_product on product_option (product_id);
create index idx_stock_history_option on stock_history (option_id);
create index idx_product_image_product on product_image (product_id);
create index idx_product_stop_request_product on product_stop_request (product_id);

-- 상품마다 심사 중인 요청은 하나만 둔다. 같은 요청이 동시에 두 번 들어와도 하나만 저장된다
create unique index uk_product_stop_request_pending
   on product_stop_request (product_id)
   where status = 'PENDING';

alter table category
   add constraint fk_category_parent_id
   foreign key (parent_id)
   references category;

alter table product
   add constraint fk_product_category_id
   foreign key (category_id)
   references category;

alter table product_option
   add constraint fk_product_option_product_id
   foreign key (product_id)
   references product;

alter table product_image
   add constraint fk_product_image_product_id
   foreign key (product_id)
   references product;

alter table product_stop_request
   add constraint fk_product_stop_request_product_id
   foreign key (product_id)
   references product;

alter table stock_history
   add constraint fk_stock_history_option_id
   foreign key (option_id)
   references product_option;

-- ── 주문 ──

create table cart (
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    member_id bigint not null unique,
    updated_at timestamp(6) not null,
    primary key (id)
);

create table cart_item (
    quantity integer not null,
    selected boolean not null,
    cart_id bigint not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    option_id bigint not null,
    updated_at timestamp(6) not null,
    primary key (id),
    constraint uk_cart_item_option unique (cart_id, option_id)
);

create table market_order (
    buyer_id bigint not null,
    canceled_at timestamp(6),
    confirmed_at timestamp(6),
    created_at timestamp(6) not null,
    expires_at timestamp(6) not null,
    id bigint generated by default as identity,
    paid_at timestamp(6),
    return_rejected_at timestamp(6),
    return_requested_at timestamp(6),
    returned_at timestamp(6),
    total_price bigint not null,
    updated_at timestamp(6) not null,
    version bigint not null,
    cancel_type varchar(20),
    confirm_type varchar(20),
    return_reason_code varchar(30),
    status varchar(30) not null,
    order_number varchar(40) not null unique,
    return_reason varchar(300),
    return_reject_reason varchar(300),
    -- 주문 생성 중복 호출 처리 키. 키 없이 만든 주문은 null
    idempotency_key varchar(64),
    primary key (id)
);

create table market_order_item (
    quantity integer not null,
    restore_stock boolean,
    cart_item_id bigint,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    line_amount bigint not null,
    option_id bigint not null,
    order_id bigint not null,
    product_id bigint not null,
    seller_id bigint not null,
    unit_price bigint not null,
    updated_at timestamp(6) not null,
    option_name varchar(50) not null,
    product_name varchar(100) not null,
    seller_name varchar(100) not null,
    primary key (id),
    constraint uk_market_order_item_option unique (order_id, option_id)
);

create table order_status_history (
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    order_id bigint not null,
    updated_at timestamp(6) not null,
    from_status varchar(30),
    to_status varchar(30) not null,
    reason varchar(300),
    primary key (id)
);

-- 구매자별로 주문 키가 겹치지 않게 한다 (null끼리는 겹쳐도 된다)
create unique index uk_market_order_buyer_idempotency on market_order (buyer_id, idempotency_key);
-- 판매자 주문 항목 조회: seller_id로 찾고 주문을 조인한다
create index idx_market_order_item_seller on market_order_item (seller_id, order_id);

alter table cart_item
   add constraint fk_cart_item_cart_id
   foreign key (cart_id)
   references cart;

alter table market_order_item
   add constraint fk_market_order_item_order_id
   foreign key (order_id)
   references market_order;

alter table order_status_history
   add constraint fk_order_status_history_order_id
   foreign key (order_id)
   references market_order;

-- ── 이벤트 (서비스마다 자기 스키마에 둔다) ──

-- Outbox: 비즈니스 변경과 같은 트랜잭션에 이벤트를 저장해 두고, 릴레이가 나중에 발행한다
create table outbox_event (
    aggregate_id bigint not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    occurred_at timestamp(6) not null,
    published_at timestamp(6),
    retry_count integer not null default 0,
    updated_at timestamp(6) not null,
    event_id uuid not null,
    aggregate_type varchar(30) not null,
    event_type varchar(100) not null,
    status varchar(20) not null,
    payload jsonb not null,
    primary key (id),
    constraint uk_outbox_event_event_id unique (event_id)
);

create index idx_outbox_event_pending
   on outbox_event (id)
   where status = 'PENDING';

create index idx_outbox_event_aggregate
   on outbox_event (aggregate_type, aggregate_id);

-- Kafka 컨슈머가 처리한 이벤트 기록. 같은 이벤트를 두 번 받아도 한 번만 처리하게 한다
create table processed_event (
    event_id uuid not null,
    consumer varchar(100) not null,
    processed_at timestamp(6) not null,
    primary key (event_id, consumer)
);

-- ── 기본 카테고리 (기획서 1장) ──
-- 카테고리가 하나라도 있으면 넣지 않는다. 넣은 순서가 정렬 순서가 된다 (대분류·소분류 모두 0부터)
do $$
begin
    if exists (select 1 from category) then
        return;
    end if;

    insert into category (name, parent_id, sort_order, is_active, created_at, updated_at)
    values ('뷰티', null, 0, true, now(), now()),
           ('의류', null, 1, true, now(), now());

    insert into category (name, parent_id, sort_order, is_active, created_at, updated_at)
    select child.name, root.id, child.sort_order, true, now(), now()
    from (values ('뷰티', '메이크업', 0), ('뷰티', '바디케어', 1), ('뷰티', '선케어', 2), ('뷰티', '마스크팩', 3),
                 ('뷰티', '클렌징', 4), ('뷰티', '스킨케어', 5), ('뷰티', '헤어케어', 6), ('뷰티', '건강식품', 7),
                 ('의류', '상의', 0), ('의류', '아우터', 1), ('의류', '바지', 2), ('의류', '원피스/스커트', 3),
                 ('의류', '신발', 4), ('의류', '가방', 5), ('의류', '모자', 6), ('의류', '소품', 7))
             as child(root_name, name, sort_order)
             join category root on root.parent_id is null and root.name = child.root_name;
end $$;
