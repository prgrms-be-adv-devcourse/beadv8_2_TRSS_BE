-- 상품 기간 할인. 판매자가 할인가와 기간을 정하면 그 기간에는 모든 구매자에게 할인가를 적용한다.
-- 할인은 상품 가격(기본가)에만 적용하고, 옵션 추가금은 할인한 기본가에 그대로 더한다.
-- 적용 중인지는 조회 시각으로 계산한다(starts_at <= now < ends_at, 삭제되지 않음). 스케줄러로 상태를 바꾸지 않는다.
-- 한 상품의 할인 기간은 겹칠 수 없다. 상품을 쓰기 잠금한 뒤 애플리케이션이 검사한다.
create table product_discount (
    id bigint generated by default as identity,
    product_id bigint not null,
    sale_price bigint not null,
    starts_at timestamp(6) not null,
    ends_at timestamp(6) not null,
    deleted_at timestamp(6),
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id),
    constraint ck_product_discount_sale_price check (sale_price > 0),
    constraint ck_product_discount_period check (starts_at < ends_at)
);

alter table product_discount
   add constraint fk_product_discount_product_id
   foreign key (product_id)
   references product;

-- 상품별 할인 조회(적용 중인 할인, 기간 겹침 검사, 판매자 할인 목록)
create index idx_product_discount_product on product_discount (product_id, starts_at);
