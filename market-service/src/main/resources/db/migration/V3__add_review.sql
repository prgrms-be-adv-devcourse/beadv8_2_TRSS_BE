-- 상품 리뷰. 구매 확정된 주문 항목 하나에 한 건만 둔다 (삭제한 리뷰도 포함해서, 지우고 다시 쓸 수 없다)
-- 상품·주문 항목은 다른 컨텍스트라 FK 없이 ID로만 참조한다
create table review (
    rating integer not null,
    created_at timestamp(6) not null,
    deleted_at timestamp(6),
    id bigint generated by default as identity,
    member_id bigint not null,
    option_id bigint not null,
    order_item_id bigint not null,
    product_id bigint not null,
    updated_at timestamp(6) not null,
    reviewer_name varchar(50) not null,
    option_name varchar(50) not null,
    content varchar(1000) not null,
    primary key (id),
    constraint uk_review_order_item unique (order_item_id),
    constraint ck_review_rating check (rating between 1 and 5)
);

-- 상품별 리뷰 목록 (최신순)·평점 요약
create index idx_review_product on review (product_id, id);

-- 내 리뷰 목록 (최신순)
create index idx_review_member on review (member_id, id);
