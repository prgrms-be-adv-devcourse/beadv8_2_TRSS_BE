-- 챗봇 대화 기록. 회원별 대화 하나에 질문·답변 메시지가 쌓인다.
-- 같은 대화의 최근 메시지를 프롬프트에 넣어 이어지는 질문에 답하고, 최근 질문은 FAQ 검색에도 붙인다.
-- enum 값에는 CHECK 제약을 두지 않는다(다른 서비스와 같은 규칙).
create table chat_conversation (
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    last_message_at timestamp(6) not null,   -- 마지막 메시지 시각. 대화 목록을 이 순서로 보여 준다
    member_id bigint not null,
    updated_at timestamp(6) not null,
    title varchar(100) not null,             -- 첫 질문(100자까지). 대화 목록에 보인다
    primary key (id)
);
-- 내 대화 목록(최근 대화 순)
create index idx_chat_conversation_member_id on chat_conversation (member_id, last_message_at desc, id desc);

create table chat_message (
    conversation_id bigint not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    updated_at timestamp(6) not null,
    answer_type varchar(20),                 -- 답변을 만든 방식(ChatAnswerType). 질문 메시지는 null
    role varchar(20) not null,               -- USER(질문), ASSISTANT(답변)
    content text not null,
    source_faq_ids bigint[] not null,        -- 답변 근거 FAQ ID(유사도 높은 순). FAQ는 지우지 않으므로 나중에도 찾을 수 있다
    primary key (id)
);
-- 대화의 메시지를 순서대로(최근 N개 포함)
create index idx_chat_message_conversation_id on chat_message (conversation_id, id);

alter table if exists chat_message
   add constraint fk_chat_message_conversation_id
   foreign key (conversation_id)
   references chat_conversation;
