-- 챗봇이 답변 근거로 쓰는 FAQ. 한 행이 벡터 검색의 문서 하나다.
-- 임베딩은 OpenAI text-embedding-3-small(1536차원). 임베딩하는 글은 질문 + 줄바꿈 + 답변이다(카테고리는 검색 필터로만 쓴다).
-- 근사 인덱스(HNSW 등)는 두지 않는다: FAQ는 수십 건이라 순차 비교로 정확히 찾고, 노출 여부 필터를 같은 SQL에 걸어도 결과 수가 줄지 않는다.
create table faq (
    visible boolean not null,             -- false면 챗봇 검색에서 빠진다(관리자가 내림)
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    updated_at timestamp(6) not null,
    category varchar(20) not null,        -- 카테고리 코드(FaqCategory)
    embedding_source_hash varchar(64) not null,   -- 임베딩한 글(질문 + 줄바꿈 + 답변)의 SHA-256 hex. 바뀌면 임베딩을 지우고 다시 만든다
    question varchar(200) not null,
    answer text not null,
    embedding vector(1536),               -- null이면 아직 임베딩 전(스케줄러가 채움). 검색에서 빠진다
    primary key (id)
);

-- 임베딩을 기다리는 FAQ (스케줄러가 찾는다)
create index idx_faq_embedding_pending on faq (id) where embedding is null;
