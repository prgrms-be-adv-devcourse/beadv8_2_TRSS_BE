-- 회원 뷰티 프로필(설문). 회원당 1행이고 다시 저장하면 덮어쓴다.
-- 값은 모두 ai 코드표(enum) 이름이다. 한글 라벨은 저장하지 않는다.
-- 여러 개인 답은 text[]로 둔다. 추천 SQL이 배열 연산자(&&)로 피하는 성분을 거른다.
-- enum 값에는 CHECK 제약을 두지 않는다(다른 서비스와 같은 규칙).
create table beauty_profile (
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    member_id bigint not null,
    updated_at timestamp(6) not null,
    skin_type varchar(20) not null,
    concerns text[] not null,
    preferred_ingredients text[] not null,
    avoided_ingredients text[] not null,
    interest_categories text[] not null,
    primary key (id),
    constraint uk_beauty_profile_member_id unique (member_id)
);
