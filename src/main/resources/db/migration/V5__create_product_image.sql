-- 상품 이미지: 대표 이미지(THUMBNAIL) 1개와 상세 이미지(DETAIL) 최대 10개.
-- 전체 URL이 아니라 저장소 안의 키(예: products/12/uuid.png)만 저장한다.
-- URL은 응답할 때 저장소 구현(로컬·S3)이 만들므로, 저장소나 도메인이 바뀌어도 데이터를 고치지 않는다.

create table product_image (
    sort_order integer not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    product_id bigint not null,
    updated_at timestamp(6) not null,
    image_type varchar(20) not null check (image_type in ('THUMBNAIL','DETAIL')),
    image_key varchar(300) not null,
    primary key (id)
);

create index idx_product_image_product
   on product_image (product_id);

alter table product_image
   add constraint fk_product_image_product_id
   foreign key (product_id)
   references product;
