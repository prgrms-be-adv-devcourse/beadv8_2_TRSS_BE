-- 초기 스키마 (Flyway 도입 시점의 엔티티 기준, Hibernate DDL로 생성 후 정리)
-- 이미 머지된 마이그레이션 파일은 수정하지 않고, 변경은 새 V{번호}__{설명}.sql로 추가한다.
-- enum 컬럼에는 허용 값 CHECK 제약을 두지 않는다. 값 검증은 @Enumerated(STRING)이 맡고,
-- enum 값을 추가할 때마다 마이그레이션이 필요해지는 것을 피한다.
-- Spring Batch 메타 테이블은 spring.batch.jdbc.initialize-schema로 따로 만든다.

create table cart (
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    member_id bigint not null unique,
    updated_at timestamp(6) not null,
    primary key (id)
);

create table cart_item (
    quantity integer not null,
    selected boolean not null,
    cart_id bigint not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    option_id bigint not null,
    updated_at timestamp(6) not null,
    primary key (id),
    constraint uk_cart_item_option unique (cart_id, option_id)
);

create table category (
    is_active boolean not null,
    sort_order integer not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    parent_id bigint,
    updated_at timestamp(6) not null,
    name varchar(50) not null,
    primary key (id),
    constraint uk_category_parent_name unique (parent_id, name)
);

create table market_order (
    buyer_id bigint not null,
    canceled_at timestamp(6),
    confirmed_at timestamp(6),
    created_at timestamp(6) not null,
    expires_at timestamp(6) not null,
    id bigint generated by default as identity,
    paid_at timestamp(6),
    return_rejected_at timestamp(6),
    return_requested_at timestamp(6),
    returned_at timestamp(6),
    total_price bigint not null,
    updated_at timestamp(6) not null,
    version bigint not null,
    cancel_type varchar(20),
    confirm_type varchar(20),
    return_reason_code varchar(30),
    status varchar(30) not null,
    order_number varchar(40) not null unique,
    return_reason varchar(300),
    return_reject_reason varchar(300),
    primary key (id)
);

create table market_order_item (
    quantity integer not null,
    restore_stock boolean,
    cart_item_id bigint,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    line_amount bigint not null,
    option_id bigint not null,
    order_id bigint not null,
    product_id bigint not null,
    seller_id bigint not null,
    unit_price bigint not null,
    updated_at timestamp(6) not null,
    option_name varchar(50) not null,
    product_name varchar(100) not null,
    seller_name varchar(100) not null,
    primary key (id),
    constraint uk_market_order_item_option unique (order_id, option_id)
);

create table member (
    created_at timestamp(6) not null,
    deleted_at timestamp(6),
    id bigint generated by default as identity,
    updated_at timestamp(6) not null,
    name varchar(20) not null,
    role varchar(20) not null,
    status varchar(20) not null,
    email varchar(100) not null unique,
    password varchar(255) not null,
    primary key (id)
);

create table order_status_history (
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    order_id bigint not null,
    updated_at timestamp(6) not null,
    from_status varchar(30),
    to_status varchar(30) not null,
    reason varchar(300),
    primary key (id)
);

create table payment (
    amount bigint not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    member_id bigint not null,
    order_id bigint not null,
    paid_at timestamp(6),
    refunded_at timestamp(6),
    updated_at timestamp(6) not null,
    wallet_id bigint not null,
    status varchar(40) not null,
    idempotency_key varchar(100) not null unique,
    fail_reason varchar(300),
    primary key (id)
);

create table product (
    category_id bigint not null,
    created_at timestamp(6) not null,
    deleted_at timestamp(6),
    id bigint generated by default as identity,
    price bigint not null,
    seller_id bigint not null,
    stopped_at timestamp(6),
    updated_at timestamp(6) not null,
    version bigint not null,
    status varchar(20) not null,
    stopped_by varchar(20),
    name varchar(100) not null,
    stopped_reason varchar(300),
    description TEXT not null,
    primary key (id)
);

create table product_option (
    stock integer not null,
    created_at timestamp(6) not null,
    deleted_at timestamp(6),
    id bigint generated by default as identity,
    product_id bigint not null,
    updated_at timestamp(6) not null,
    name varchar(50) not null,
    primary key (id)
);

create table seller (
    applied_at timestamp(6) not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    member_id bigint not null unique,
    updated_at timestamp(6) not null,
    version bigint not null,
    business_number varchar(20) unique,
    phone_number varchar(20) not null,
    bank_name varchar(30) not null,
    status varchar(30) not null,
    account_holder varchar(50) not null,
    representative_name varchar(50) not null,
    business_name varchar(100) not null,
    account_number varchar(255) not null,
    primary key (id)
);

create table seller_status_history (
    account_last4 varchar(4),
    changed_at timestamp(6) not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    seller_id bigint not null,
    updated_at timestamp(6) not null,
    business_number varchar(20),
    from_status varchar(30),
    to_status varchar(30) not null,
    representative_name varchar(50),
    business_name varchar(100),
    reason varchar(255),
    primary key (id)
);

create table settlement (
    item_count integer not null,
    retry_count integer not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    next_retry_at timestamp(6),
    paid_at timestamp(6),
    payout_amount bigint not null,
    seller_id bigint not null,
    total_fee bigint not null,
    total_sale_price bigint not null,
    updated_at timestamp(6) not null,
    wallet_tx_id bigint,
    status varchar(20) not null,
    idempotency_key varchar(100),
    hold_reason varchar(300),
    last_fail_reason varchar(300),
    settlement_month CHAR(7) not null,
    primary key (id),
    constraint uk_settlement_seller_month unique (seller_id, settlement_month),
    constraint uk_settlement_idempotency_key unique (idempotency_key)
);

create table settlement_candidate (
    fee_rate integer not null,
    confirmed_at timestamp(6) not null,
    created_at timestamp(6) not null,
    fee bigint not null,
    id bigint generated by default as identity,
    order_id bigint not null,
    order_item_id bigint not null,
    outbox_event_id bigint,
    payout_amount bigint not null,
    sale_price bigint not null,
    seller_id bigint not null,
    settlement_id bigint,
    updated_at timestamp(6) not null,
    status varchar(20) not null,
    excluded_reason varchar(300),
    settlement_month CHAR(7) not null,
    primary key (id),
    constraint uk_candidate_order_item unique (order_item_id)
);

create table settlement_process_history (
    attempt_no integer not null,
    batch_execution_id bigint,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    processed_at timestamp(6) not null,
    target_id bigint,
    updated_at timestamp(6) not null,
    result varchar(20) not null,
    target_type varchar(20) not null,
    trigger_type varchar(20) not null,
    stage varchar(30) not null,
    error_code varchar(100),
    admin_reason varchar(300),
    fail_reason varchar(300),
    primary key (id)
);

create table stock_history (
    change_qty integer not null,
    stock_after integer not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    option_id bigint not null,
    order_id bigint,
    order_item_id bigint,
    updated_at timestamp(6) not null,
    change_type varchar(20) not null,
    primary key (id),
    constraint uk_stock_history_order_item_change_type unique (order_item_id, change_type)
);

create table topup (
    amount bigint not null,
    approved_at timestamp(6),
    canceled_at timestamp(6),
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    member_id bigint not null,
    remaining_amount bigint not null,
    updated_at timestamp(6) not null,
    wallet_id bigint not null,
    status varchar(30) not null,
    toss_order_id varchar(64) not null unique,
    payment_key varchar(200) unique,
    fail_reason varchar(300),
    primary key (id)
);

create table wallet (
    balance bigint not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    member_id bigint not null unique,
    updated_at timestamp(6) not null,
    primary key (id)
);

create table wallet_holding (
    amount bigint not null,
    created_at timestamp(6) not null,
    held_at timestamp(6) not null,
    id bigint generated by default as identity,
    order_id bigint not null unique,
    payment_id bigint not null unique,
    released_at timestamp(6),
    settled_amount bigint not null,
    settled_at timestamp(6),
    updated_at timestamp(6) not null,
    wallet_id bigint not null,
    status varchar(20) not null,
    primary key (id)
);

create table wallet_transaction (
    amount bigint not null,
    balance_after bigint not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    reference_id bigint not null,
    updated_at timestamp(6) not null,
    wallet_id bigint not null,
    type varchar(20) not null,
    reference_type varchar(30) not null,
    idempotency_key varchar(100) not null unique,
    primary key (id)
);

create index idx_payment_order
   on payment (order_id, created_at);

create index idx_seller_status_history_seller
   on seller_status_history (seller_id, id);

create index idx_settlement_status
   on settlement (status, settlement_month);

create index idx_candidate_settlement
   on settlement_candidate (settlement_id);

create index idx_candidate_seller_status
   on settlement_candidate (seller_id, status, settlement_month);

create index idx_history_target
   on settlement_process_history (target_type, target_id);

create index idx_topup_member
   on topup (member_id, created_at);

create index idx_wallet_holding_wallet
   on wallet_holding (wallet_id, status);

create index idx_wallet_tx_wallet
   on wallet_transaction (wallet_id, created_at);

create index idx_wallet_tx_reference
   on wallet_transaction (reference_type, reference_id);

