-- 소셜 계정 연결: 이메일로 가입한 회원에게 카카오 등 소셜 계정을 연결해 로그인 수단으로 쓴다
-- 소셜 계정으로 새로 가입하는 기능은 없으므로 회원은 항상 이메일·비밀번호를 가진다

create table member_social_account (
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    member_id bigint not null,
    updated_at timestamp(6) not null,
    provider varchar(20) not null,
    provider_user_id varchar(100) not null,
    primary key (id)
);

-- 소셜 계정 하나는 한 회원에게만 연결된다 (로그인할 때 이 조건으로 회원을 찾는다)
alter table member_social_account
   add constraint uk_member_social_account_provider_user unique (provider, provider_user_id);

-- 회원은 제공자별로 계정을 하나만 연결한다
alter table member_social_account
   add constraint uk_member_social_account_member_provider unique (member_id, provider);

alter table member_social_account
   add constraint fk_member_social_account_member_id
   foreign key (member_id)
   references member;
