-- 충전 차감 내역: 결제할 때 오래된 충전 건부터 차감하고, 충전 건마다 어느 결제에 얼마를 썼는지 남긴다.
-- 충전 건의 남은 금액(topup.remaining_amount)이 충전 금액과 같을 때만 토스 취소(미사용 충전 환불)가 가능하므로,
-- 결제가 충전 건을 쓴 기록이 있어야 이미 쓴 충전을 환불받는 일을 막을 수 있다.

create table topup_usage (
    amount bigint not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    payment_id bigint not null,
    topup_id bigint not null,
    updated_at timestamp(6) not null,
    primary key (id)
);

create index idx_topup_usage_topup
   on topup_usage (topup_id);

create index idx_topup_usage_payment
   on topup_usage (payment_id);

alter table topup_usage
   add constraint fk_topup_usage_topup_id
   foreign key (topup_id)
   references topup;

alter table topup_usage
   add constraint fk_topup_usage_payment_id
   foreign key (payment_id)
   references payment;
