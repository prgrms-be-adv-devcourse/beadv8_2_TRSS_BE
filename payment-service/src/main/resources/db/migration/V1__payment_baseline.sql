-- payment 스키마 초기 상태. 모놀리스 마이그레이션 V1~V16 중 결제 테이블(V1·V3·V8·V9·V16)과 outbox·처리 기록(V12·V14)만 모아 최종 형태로 정리했다.
-- 운영 DB는 테이블을 public에서 payment로 옮긴 뒤 baseline-on-migrate로 이 파일을 적용된 것으로 기록한다.
-- 그래서 이 파일은 옮긴 뒤의 운영 테이블과 같아야 한다. 이후 변경은 V2부터 새 파일로 추가한다.
-- enum 컬럼에는 허용 값 CHECK 제약을 두지 않는다(모놀리스 V1과 같은 규칙).
-- 회원·주문 테이블은 다른 서비스 스키마에 있어 외래 키를 걸지 않는다(member_id, order_id는 값만 저장).

-- ── 지갑 ──

create table wallet (
    balance bigint not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    member_id bigint not null unique,
    updated_at timestamp(6) not null,
    primary key (id)
);

create table wallet_transaction (
    amount bigint not null,
    balance_after bigint not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    reference_id bigint not null,
    updated_at timestamp(6) not null,
    wallet_id bigint not null,
    type varchar(20) not null,
    reference_type varchar(30) not null,
    idempotency_key varchar(100) not null unique,
    primary key (id)
);

-- ── 주문 결제 ──

create table payment (
    amount bigint not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    member_id bigint not null,
    order_id bigint not null,
    paid_at timestamp(6),
    refunded_at timestamp(6),
    updated_at timestamp(6) not null,
    wallet_id bigint not null,
    status varchar(40) not null,
    idempotency_key varchar(100) not null unique,
    fail_reason varchar(300),
    order_number varchar(40) not null,        -- V8 (모놀리스에서 나중에 추가한 컬럼이라 운영 테이블과 같은 순서로 뒤에 둠)
    canceled_at timestamp(6),                 -- V16
    primary key (id)
);

-- 주문당 "해제되지 않은 홀딩"은 1개 (V16). 취소된 결제의 홀딩(RELEASED)이 있어도 같은 주문을 다시 결제할 수 있다
create table wallet_holding (
    amount bigint not null,
    created_at timestamp(6) not null,
    held_at timestamp(6) not null,
    id bigint generated by default as identity,
    order_id bigint not null,
    payment_id bigint not null unique,
    released_at timestamp(6),
    settled_amount bigint not null,
    settled_at timestamp(6),
    updated_at timestamp(6) not null,
    wallet_id bigint not null,
    status varchar(20) not null,
    primary key (id)
);

-- ── 충전 ──

create table topup (
    amount bigint not null,
    approved_at timestamp(6),
    canceled_at timestamp(6),
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    member_id bigint not null,
    remaining_amount bigint not null,
    updated_at timestamp(6) not null,
    wallet_id bigint not null,
    status varchar(30) not null,
    toss_order_id varchar(64) collate "C" not null unique,   -- V9: 충전번호 앞부분 일치 검색이 유니크 인덱스를 타도록 바이트 순서
    payment_key varchar(200) unique,
    fail_reason varchar(300),
    primary key (id)
);

-- 결제가 어느 충전 건에서 얼마를 썼는지 (V3)
create table topup_usage (
    amount bigint not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    payment_id bigint not null,
    topup_id bigint not null,
    updated_at timestamp(6) not null,
    primary key (id)
);

-- ── Outbox·처리 기록 (common의 EventPublisher·ProcessedEvents가 쓴다, V12·V14와 같은 정의) ──

create table outbox_event (
    aggregate_id bigint not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    occurred_at timestamp(6) not null,
    published_at timestamp(6),
    retry_count integer not null default 0,
    updated_at timestamp(6) not null,
    event_id uuid not null,
    aggregate_type varchar(30) not null,
    event_type varchar(100) not null,
    status varchar(20) not null,
    payload jsonb not null,
    primary key (id)
);

alter table outbox_event
   add constraint uk_outbox_event_event_id unique (event_id);

create table processed_event (
    event_id uuid not null,
    consumer varchar(100) not null,
    processed_at timestamp(6) not null,
    primary key (event_id, consumer)
);

-- ── 인덱스 ──

create index idx_wallet_tx_wallet
   on wallet_transaction (wallet_id, created_at);

create index idx_wallet_tx_reference
   on wallet_transaction (reference_type, reference_id);

create index idx_payment_order
   on payment (order_id, created_at);

create index idx_payment_order_number
   on payment (order_number);

create unique index uk_wallet_holding_order_active
   on wallet_holding (order_id)
   where status <> 'RELEASED';

create index idx_wallet_holding_wallet
   on wallet_holding (wallet_id, status);

create index idx_topup_member
   on topup (member_id, created_at);

create index idx_topup_usage_topup
   on topup_usage (topup_id);

create index idx_topup_usage_payment
   on topup_usage (payment_id);

create index idx_outbox_event_pending
   on outbox_event (id)
   where status = 'PENDING';

create index idx_outbox_event_aggregate
   on outbox_event (aggregate_type, aggregate_id);

-- ── 외래 키 (결제 스키마 안의 테이블끼리만) ──

alter table wallet_transaction
   add constraint fk_wallet_transaction_wallet_id
   foreign key (wallet_id)
   references wallet;

alter table payment
   add constraint fk_payment_wallet_id
   foreign key (wallet_id)
   references wallet;

alter table wallet_holding
   add constraint fk_wallet_holding_payment_id
   foreign key (payment_id)
   references payment;

alter table wallet_holding
   add constraint fk_wallet_holding_wallet_id
   foreign key (wallet_id)
   references wallet;

alter table topup
   add constraint fk_topup_wallet_id
   foreign key (wallet_id)
   references wallet;

alter table topup_usage
   add constraint fk_topup_usage_topup_id
   foreign key (topup_id)
   references topup;

alter table topup_usage
   add constraint fk_topup_usage_payment_id
   foreign key (payment_id)
   references payment;
