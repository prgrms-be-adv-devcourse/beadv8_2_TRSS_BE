-- 배송(주문서 1개당 1건)과 배송 항목(주문 항목 스냅샷). enum 컬럼에는 CHECK 제약을 두지 않는다.
-- 배송지(수령인·연락처·주소·요청사항)는 결제 시점 주문 스냅샷이다. 로그에 남기지 않는다.
create table delivery (
    id bigint generated by default as identity,
    order_id bigint not null,
    order_number varchar(40) not null,
    buyer_id bigint not null,
    status varchar(20) not null,
    paid_at timestamp(6) not null,
    receiver_name varchar(50) not null,
    receiver_phone varchar(20) not null,
    zip_code varchar(10) not null,
    address varchar(200) not null,
    address_detail varchar(200),
    request_message varchar(100),
    courier varchar(20),
    tracking_number varchar(30),
    shipped_at timestamp(6),
    delivered_at timestamp(6),
    webhook_expires_at timestamp(6),
    tracking_check_requested_at timestamp(6),
    last_tracking_status varchar(40),
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id),
    constraint uk_delivery_order unique (order_id),
    -- 콜백의 (carrierId, trackingNumber)로 배송 건을 찾는다. READY(null)는 여러 건이어도 된다
    constraint uk_delivery_tracking unique (courier, tracking_number)
);

-- 물류 목록: 상태별, READY는 결제 오래된 순
create index idx_delivery_status on delivery (status, paid_at);
-- 확인 워커(PR 3-B): 콜백을 받아 조회를 기다리는 배송 건
create index idx_delivery_check on delivery (tracking_check_requested_at)
    where status = 'SHIPPED' and tracking_check_requested_at is not null;
-- 웹훅 등록·재등록 스케줄러(PR 3-B)
create index idx_delivery_webhook on delivery (webhook_expires_at) where status = 'SHIPPED';

create table delivery_item (
    id bigint generated by default as identity,
    delivery_id bigint not null,
    order_item_id bigint not null,
    product_id bigint not null,
    option_id bigint not null,
    seller_id bigint not null,
    seller_name varchar(100) not null,
    product_name varchar(100) not null,
    option_name varchar(50) not null,
    quantity integer not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    primary key (id),
    constraint uk_delivery_item_order_item unique (order_item_id)
);

create index idx_delivery_item_delivery on delivery_item (delivery_id);

alter table delivery_item
   add constraint fk_delivery_item_delivery_id foreign key (delivery_id) references delivery;
