-- notification 스키마 초기 상태. 새로 만드는 서비스라 운영에서 옮겨 올 테이블이 없고, 빈 스키마에 V1부터 적용한다.
-- 이후 변경은 V2부터 새 파일로 추가한다.
-- enum 컬럼에는 허용 값 CHECK 제약을 두지 않는다(모놀리스 V1과 같은 규칙).

-- Outbox: 알림은 이벤트를 발행하지 않지만, common의 OutboxEvent 엔티티가 등록되어 ddl-auto: validate가 이 테이블을 확인한다
create table outbox_event (
    aggregate_id bigint not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    occurred_at timestamp(6) not null,
    published_at timestamp(6),
    retry_count integer not null default 0,
    updated_at timestamp(6) not null,
    event_id uuid not null,
    aggregate_type varchar(30) not null,
    event_type varchar(100) not null,
    status varchar(20) not null,
    payload jsonb not null,
    primary key (id),
    constraint uk_outbox_event_event_id unique (event_id)
);

create index idx_outbox_event_pending
   on outbox_event (id)
   where status = 'PENDING';

create index idx_outbox_event_aggregate
   on outbox_event (aggregate_type, aggregate_id);

-- Kafka 컨슈머가 처리한 이벤트 기록. 같은 이벤트를 두 번 받아도 한 번만 처리하게 한다
create table processed_event (
    event_id uuid not null,
    consumer varchar(100) not null,
    processed_at timestamp(6) not null,
    primary key (event_id, consumer)
);
